def key(collection: str, object_id: str) -> str:
    # IDs can contain '/', so split only at the first delimiter.
    return collection + KEY_SEPARATOR + object_id


def split_key(value: str) -> tuple[str, str]:
    parts = value.split(KEY_SEPARATOR, 1)
    if len(parts) != 2 or not all(parts):
        raise ValueError("invalid record key")
    return parts[0], parts[1]


def index(rows: list[Row] | list[dict]) -> dict[str, dict]:
    result = {}
    identities = set()
    for value in rows:
        row = value if isinstance(value, Row) else Row.model_validate(value)
        if row.key in result or row.object_id in identities:
            raise ValueError("duplicate or cross-collection identity: " + row.key)
        if row.collection in KNOWLEDGE_COLLECTIONS:
            _, id_field = KNOWLEDGE_COLLECTIONS[row.collection]
            if row.payload.get(id_field) != row.object_id:
                raise ValueError("payload identity differs: " + row.key)
        result[row.key] = deepcopy(row.payload)
        identities.add(row.object_id)
    return result


def rows(states: dict[str, dict]) -> list[dict]:
    return [dict(collection=split_key(k)[0], object_id=split_key(k)[1], payload=p)
            for k, p in sorted(states.items())]


def fingerprint(states: dict[str, dict], *, collections: list[str] | None = None) -> str:
    # Bind even currently empty collections: inserting a record there after
    # review must be detected by the advisory-locked SQL boundary too.
    # One traversal, not one whole-library traversal per collection. Keep the
    # exact old wire fingerprint, including empty collections, unknown included
    # collections and duplicate payload hashes. Explicit cuts must not hash rows
    # outside the cut. This remains a FULL-cut operation, not an incremental
    # current-state proof: callers must not mistake this optimization for O(D).
    implicit = collections is None
    hashes = {c: [] for c in (KNOWLEDGE_COLLECTIONS if implicit else collections)}
    for k, payload in states.items():
        collection = split_key(k)[0]
        if implicit:
            hashes.setdefault(collection, [])
        if collection in hashes:
            hashes[collection].append(sha256_json(payload))
    return sha256_json({c: sorted(hashes[c]) for c in sorted(hashes)})


def verify_file(binding: FileBinding | dict) -> Path:
    b = binding if isinstance(binding, FileBinding) else FileBinding.model_validate(binding)
    path = Path(b.path)
    if not path.is_absolute() or not path.is_file() or file_sha256(path) != b.file_sha256:
        raise ValueError("physical file missing or changed: " + str(path))
    return path


def bound_bytes(binding: FileBinding | dict, snapshots: dict | None = None) -> bytes:
    b = binding if isinstance(binding, FileBinding) else FileBinding.model_validate(binding)
    if snapshots is None:
        raw = verify_file(b).read_bytes()
    else:
        raw = bytes.fromhex(snapshots[b.path + ":" + b.file_sha256])
    if hashlib.sha256(raw).hexdigest() != b.file_sha256:
        raise ValueError("source changed while reading or archived source SHA drift")
    return raw


def source_snapshot(binding: FileBinding | dict, snapshots: dict | None = None, *, source: dict | None = None) -> dict:
    import json
    raw = bound_bytes(binding, snapshots)
    if source and source.get("source_type") == "notes_manuscript":
        from backend.pipeline.knowledge_source import markdown_blocks
        from backend.pipeline.source_projection import script_from_markdown_blocks
        if source.get("visual_source_assets"):
            raise ValueError("Claim issue visual source requires a separately scoped adapter")
        projection = project_script(script_from_markdown_blocks(markdown_blocks(raw.decode("utf-8"))))
    else:
        document = json.loads(raw)
        projection = project_script(document.get("script") if isinstance(document, dict) else document)
    if projection.visual_blocks:
        raise ValueError("visual source changes require a separately scoped visual adapter")
    return {
        "file": FileBinding.model_validate(binding).model_dump() if isinstance(binding, dict) else binding.model_dump(),
        "body_sha256": projection.body_sha256,
        "spoken_text_sha256": projection.spoken_text_sha256,
        "editorial_structure_sha256": projection.editorial_structure_sha256,
        "paragraphs": {f"S{i:04d}": row for i, row in enumerate(projection.spoken_rows, 1)},
    }


def strings(value: Any):
    """Exact JSON values (also map keys); never fuzzy substring matching."""
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for k, v in value.items():
            yield str(k)
            yield from strings(v)
    elif isinstance(value, list):
        for v in value:
            yield from strings(v)


def dependency_index(states: dict[str, dict]) -> tuple[dict, dict]:
    owners = {split_key(k)[1]: k for k in states}
    forward, reverse = {}, defaultdict(set)
    for k, p in states.items():
        targets = {owners[v] for v in strings(p) if v in owners and owners[v] != k}
        forward[k] = targets
        for target in targets:
            reverse[target].add(k)
    return forward, reverse


def inventory(states: dict[str, dict], source_id: str) -> dict:
    """Full reverse closure; non-knowledge consumers become explicit impacts.

    CVPs are semantic boundaries: include all their direct consumers and full
    member/evidence context, but do not recursively rewrite the whole CVP graph.
    Unknown collections are included and must be unresolved, not dropped.
    """
    root = key("source_documents", source_id)
    if root not in states:
        raise ValueError("source document absent")
    forward, reverse = dependency_index(states)
    aliases = {source_id, states[root].get("transcript_id"), states[root].get("canonical_source_id")} - {None, ""}
    affected = {root} | {k for k, p in states.items()
                         if split_key(k)[0] in WRITABLE and aliases & set(strings(p))}
    queue = deque(sorted(affected))
    while queue:
        target = queue.popleft()
        for consumer in sorted(reverse[target]):
            if consumer in affected:
                continue
            affected.add(consumer)
            if split_key(consumer)[0] in WRITABLE and split_key(consumer)[0] != "canonical_viewpoints":
                queue.append(consumer)
    # Link targets are forward edges, not source consumers; every linked CVP
    # and its current revision and other members still require full context.
    viewpoints = {key("canonical_viewpoints", states[k]["viewpoint_id"])
                  for k in affected if split_key(k)[0] == "viewpoint_claim_links"}
    for cv in viewpoints:
        if cv not in states:
            raise ValueError("dangling viewpoint target")
        affected.add(cv)
        affected.update(reverse[cv])
        rev = key("viewpoint_revisions", states[cv]["current_revision_id"])
        if rev not in states:
            raise ValueError("current viewpoint revision absent")
        affected.add(rev)
    context = set(affected)
    queue = deque(sorted(affected))
    while queue:
        for target in sorted(forward[queue.popleft()]):
            if target not in context:
                context.add(target)
                queue.append(target)
    return {
        "affected_keys": sorted(affected), "context_keys": sorted(context - affected),
        "unknown_keys": sorted(k for k in affected
                               if split_key(k)[0] not in WRITABLE | IMPACT_ONLY),
        "reverse_edges": {k: sorted(reverse[k]) for k in sorted(affected)},
    }


def unresolved_consumers(frozen):
    """Consume saved pre-call unknown route classification without rewriting it.

    KnowledgeRouteRecord is an existing internal output schema, not a new route
    production permission. Exact SQL pins and payloads remain unchanged.
    """
    if not frozen['inventory']['unknown_keys']:
        return []
    before = index(frozen['before_records'])
    pins = {(r['collection'], r['object_id']): r['pin'] for r in frozen.get('sql_scope', {}).get('read_pins', [])}
    unknown = []
    for k in frozen['inventory']['unknown_keys']:
        col, oid = split_key(k)
        if col != 'knowledge_routes':
            unknown.append(k); continue
        value = before[k]
        KNOWLEDGE_COLLECTIONS[col][0].model_validate(value)
        if (value.get('route_id') != oid or value.get('visibility') != 'internal'
                or value.get('review_status') in {'human_hold', 'human_review_required', 'rejected', 'withheld_unreviewed'}
                or pins.get((col, oid)) != [value['revision'], record_content_sha(value), False]
                or k not in frozen['inventory']['affected_keys']):
            raise ValueError('historical knowledge route schema/pin/hold drift')
    return unknown


def claim_inventory(states: dict[str, dict], source_id: str, claim_ids: list[str], *, retained_occurrences=()) -> dict:
    """Exact reverse impact plus all CVP members, not whole-sermon re-extraction."""
    forward, reverse = dependency_index(states)
    roots = {key("claims", cid) for cid in claim_ids}
    if len(roots) != len(claim_ids) or not roots <= states.keys():
        raise ValueError("deferred Claim identities missing/duplicated")
    doc = states[key("source_documents", source_id)]
    aliases = {source_id, doc.get("transcript_id"), doc.get("canonical_source_id")} - {None, ""}
    from backend.pipeline.claim_retained_occurrence_context import validate
    retained = validate(retained_occurrences, states, source_id, claim_ids)
    for k in roots:
        if split_key(k)[1] not in retained and (not states[k].get("occurrences") or any(not aliases.intersection(set(strings(o))) for o in states[k]["occurrences"])):
            raise ValueError("deferred Claim has foreign/ambiguous occurrence source")
    affected = roots | {key("evidence_steps", eid) for k in roots for eid in states[k].get("evidence_step_ids", [])}
    if not affected <= states.keys():
        raise ValueError("deferred Claim has missing Evidence")
    queue = deque(sorted(affected))
    while queue:
        k = queue.popleft()
        if split_key(k)[0] in {"canonical_viewpoints", "source_documents", "source_fragments"}:
            continue
        for consumer in reverse[k]:
            if consumer not in affected:
                affected.add(consumer)
                if split_key(consumer)[0] in WRITABLE:
                    queue.append(consumer)
    viewpoints = {states[k]["viewpoint_id"] for k in affected if k.startswith("viewpoint_claim_links/")}
    for vid in viewpoints:
        cv = key("canonical_viewpoints", vid)
        if cv not in states:
            raise ValueError("dangling affected CVP")
        affected.update({cv, key("viewpoint_revisions", states[cv]["current_revision_id"])})
        affected.update(reverse[cv])
    context = set(affected) | {key("source_documents", source_id)}
    context.update(key(r['historical_source_pin']['collection'], r['historical_source_pin']['object_id'])
                   for r in retained_occurrences)
    queue = deque(sorted(context))
    while queue:
        for target in forward[queue.popleft()]:
            if target not in context:
                context.add(target)
                queue.append(target)
    return {"affected_keys": sorted(affected), "context_keys": sorted(context - affected),
            "unknown_keys": sorted(k for k in affected if split_key(k)[0] not in WRITABLE | IMPACT_ONLY),
            "reverse_edges": {k: sorted(reverse[k]) for k in sorted(affected)}}


def freeze(manifest: Manifest, states: dict[str, dict], *, physical_snapshots: dict | None = None) -> dict:
    import json
    authorization = json.loads(bound_bytes(manifest.authorization, physical_snapshots))
    if not authorization.get("authorization_quote") or not authorization.get("authorization_id") or authorization.get("human_content_approval") is not False:
        raise ValueError("bounded execution authorization is not human content approval")
    if authorization.get("source_id") != manifest.source_id:
        raise ValueError("authorization belongs to another source")
    if authorization.get("permissions") != [p.model_dump() for p in manifest.permissions]:
        raise ValueError("permission set not bound to owner authorization")
    membership = json.loads(bound_bytes(manifest.accepted_membership, physical_snapshots))
    expected_groups = [{"group_key": g.group_key, "claim_ids": g.claim_ids} for g in manifest.groups]
    if [{"group_key": g["group_key"], "claim_ids": g["claim_ids"]} for g in membership.get("groups", [])] != expected_groups:
        raise ValueError("accepted group membership/order drift")
    claim_ids = [cid for g in manifest.groups for cid in g.claim_ids]
    if (len(claim_ids) != len(set(claim_ids)) or sorted(claim_ids) != sorted(manifest.campaign_claim_ids)
            or len({g.group_key for g in manifest.groups}) != len(manifest.groups)):
        raise ValueError("campaign membership is not exact-once")
    if len({p.key for p in manifest.permissions}) != len(manifest.permissions):
        raise ValueError("duplicate permissions")
    for p in manifest.permissions:
        if p.collection not in WRITABLE or len(p.fields) != len(set(p.fields)):
            raise ValueError("unsupported or duplicate field permission")
        if p.create and p.collection not in {"source_fragments", "viewpoint_revisions"}:
            raise ValueError("new judgments/identities require a separate membership decision")
        if p.collection == "viewpoint_revisions" and not p.create:
            raise ValueError("CVP content changes create a new revision; historical CVR cannot be overwritten")
        if p.create == (p.key in states):
            raise ValueError("create/update permission does not match Registry")
        if p.parent_id and (not p.create or (p.collection == "source_fragments" and p.parent_id != manifest.source_id)
                or (p.collection == "viewpoint_revisions" and key("canonical_viewpoints", p.parent_id) not in states)):
            raise ValueError("creation parent is outside the exact existing source/viewpoint identity")
    old = states[key("source_documents", manifest.source_id)]
    before = source_snapshot(manifest.before_source, physical_snapshots, source=old if manifest.claim_issue or manifest.viewpoint_scope_repair else None)
    after = [source_snapshot(b, physical_snapshots, source=old if manifest.claim_issue or manifest.viewpoint_scope_repair else None) for b in manifest.current_sources]
    if any(a["paragraphs"] != after[0]["paragraphs"] for a in after):
        raise ValueError("current source copies have different spoken bodies")
    if (old.get("locator_space") != LOCATOR_SPACE or old.get("source_body_sha256") != before["body_sha256"]
            or old.get("source_file_sha256") != before["file"]["file_sha256"]):
        raise ValueError("old physical body is not the registered spoken-body epoch")
    if Path(old.get("source_path", "")).resolve() != Path(manifest.current_sources[0].path).resolve():
        raise ValueError("primary current source must retain the registered physical locator")
    keys = set(before["paragraphs"]) | set(after[0]["paragraphs"])
    changed = sorted(k for k in keys if before["paragraphs"].get(k) != after[0]["paragraphs"].get(k))
    if not set(changed) <= set(manifest.authorized_paragraph_keys):
        raise ValueError("source change exceeds authorized paragraphs; no automatic scope expansion")
    if manifest.viewpoint_scope_repair:
        from backend.pipeline.cvp_scope_management import validate_authority, scope_inventory
        diagnosis = validate_authority(manifest, states, snapshots=physical_snapshots)
        if changed or manifest.authorized_paragraph_keys:
            raise ValueError('CVP scope repair cannot change source paragraphs')
        inv = scope_inventory(states, diagnosis['viewpoint_id'])
    elif manifest.claim_issue:
        from backend.pipeline.claim_issue_management import validate_authority
        diagnosis = validate_authority(manifest, states, snapshots=physical_snapshots)
        ids=set(diagnosis['claim_ids'])
        if diagnosis.get('scope_amendment'):
            direction=json.loads(bound_bytes(diagnosis['scope_amendment'],physical_snapshots))
            ids.update(states[key(p['collection'],p['object_id'])]['claim_id'] for p in direction['link_permissions'])
        inv = claim_inventory(states, manifest.source_id, sorted(ids),
                              retained_occurrences=diagnosis.get('retained_occurrence_context', []))
        if diagnosis.get('scope_amendment'):
            # Additional current source Claims are read-only context, never
            # campaign members or automatic new CVP identity approvals.
            forward,_=dependency_index(states)
            context=set(inv['context_keys'])|set(inv['affected_keys'])
            queue=deque(key('claims',cid) for cid in direction['context_claim_ids'])
            while queue:
                k=queue.popleft()
                if k not in states:raise ValueError('amendment context Claim is missing/retired')
                if k in context:continue
                context.add(k);queue.extend(forward[k]-context)
            inv['context_keys']=sorted(context-set(inv['affected_keys']))
    elif manifest.deferred_repair:
        from backend.pipeline.deferred_claim_repair import validate_authority
        diagnosis = validate_authority(manifest, states, snapshots=physical_snapshots)
        inv = claim_inventory(states, manifest.source_id, manifest.deferred_repair.claim_ids)
    else:
        inv = inventory(states, manifest.source_id)
    identity = {"schema_version": VERSION, "manifest": manifest.model_dump(),
                "before": before, "after": after, "registry_sha256": fingerprint(states), "inventory": inv}
    context_sources = []
    from backend.pipeline.viewpoint_evidence_source_context import load_context_source
    for k in sorted(set(inv["affected_keys"]) | set(inv["context_keys"])):
        if not k.startswith("source_documents/") or k == key("source_documents", manifest.source_id):
            continue
        source = states[k]
        if physical_snapshots is None or source.get("source_type") == "notes_manuscript":
            path, digest, projection = load_context_source(source)
        else:
            path, digest = Path(source["source_path"]), source["source_file_sha256"]
            raw = json.loads(bound_bytes({"path": str(path), "file_sha256": digest}, physical_snapshots))
            projection = project_script(raw["script"] if isinstance(raw, dict) else raw)
            if projection.body_sha256 != source.get("source_body_sha256"):
                raise ValueError("archived context body differs from registered source")
        if projection.visual_blocks:
            raise ValueError("visual context requires an explicit visual adapter")
        context_sources.append({"source_id": source["source_id"], "file": {"path": str(path), "file_sha256": digest},
            "body_sha256": projection.body_sha256,
            "paragraphs": {f"S{i:04d}": r for i, r in enumerate(projection.spoken_rows, 1)}})
    identity["context_sources"] = context_sources
    from backend.pipeline.sentence_ledger import build_inventory
    sentence_inventory = build_inventory(
        [(int(k[1:]), after[0]["paragraphs"][k]["text"]) for k in sorted(set(manifest.authorized_paragraph_keys)) if k in after[0]["paragraphs"]],
        source_id=manifest.source_id, source_sha256=after[0]["body_sha256"])
    identity["sentence_inventory"] = [s.model_dump(mode="json") for s in sentence_inventory]
    if manifest.deferred_repair:
        identity["deferred_diagnosis"] = diagnosis
    if manifest.claim_issue:
        identity["claim_issue_context"] = diagnosis
    if manifest.viewpoint_scope_repair:
        identity['viewpoint_scope_context'] = diagnosis
    archive_bindings = [manifest.before_source, *manifest.current_sources, manifest.authorization,
                        manifest.accepted_membership, *manifest.prior_updates]
    archive_bindings += [FileBinding.model_validate(s["file"]) for s in context_sources]
    if manifest.claim_issue:
        archive_bindings.append(manifest.claim_issue)
        archive_bindings.append(FileBinding.model_validate(diagnosis["policy"]))
        archive_bindings.extend(FileBinding.model_validate(r["report"]) for r in diagnosis["issues"])
        archive_bindings.extend(FileBinding.model_validate(b)
            for receipt in diagnosis.get('retained_occurrence_context', [])
            for b in receipt['authority']['bindings'])
        if diagnosis.get('scope_amendment'):
            archive_bindings.append(FileBinding.model_validate(diagnosis['scope_amendment']))
            direction=json.loads(bound_bytes(diagnosis['scope_amendment'],physical_snapshots))
            archive_bindings.extend(FileBinding.model_validate(direction[n]) for n in ('old_materials','old_packet','old_raw','new_policy'))
    if manifest.viewpoint_scope_repair:
        archive_bindings += [manifest.viewpoint_scope_repair, FileBinding.model_validate(diagnosis['policy'])]
        archive_bindings.extend(FileBinding.model_validate(b) for b in diagnosis['reports'])
    if manifest.deferred_repair:
        archive_bindings += [manifest.deferred_repair.investigation_packet, manifest.deferred_repair.handoff,
                             manifest.deferred_repair.raw_gpt, manifest.deferred_repair.raw_opus]
        if manifest.deferred_repair.provider_schema_rejection:
            archive_bindings.append(manifest.deferred_repair.provider_schema_rejection)
    identity["physical_snapshots"] = {b.path + ":" + b.file_sha256: bound_bytes(b, physical_snapshots).hex() for b in archive_bindings}
    return {**identity, "changed_paragraph_keys": changed, "update_id": "SR-" + sha256_json(identity),
            "before_records": rows(states)}


def guard_files(frozen: dict, *, historical: bool = False) -> None:
    manifest = Manifest.model_validate(frozen["manifest"])
    for b in [manifest.before_source, *manifest.current_sources, manifest.authorization, manifest.accepted_membership, *manifest.prior_updates]:
        bound_bytes(b, frozen["physical_snapshots"] if historical else None)
    for source in frozen.get("context_sources", []):
        bound_bytes(source["file"], frozen["physical_snapshots"] if historical else None)
    if manifest.claim_issue:
        context = frozen["claim_issue_context"]
        for b in [manifest.claim_issue, context["policy"], *(r["report"] for r in context["issues"])]:
            bound_bytes(b, frozen["physical_snapshots"] if historical else None)
        for receipt in context.get('retained_occurrence_context', []):
            for b in receipt['authority']['bindings']:
                bound_bytes(b, frozen['physical_snapshots'] if historical else None)
        if context.get('scope_amendment'):
            bound_bytes(context['scope_amendment'],frozen['physical_snapshots'] if historical else None)
    if manifest.viewpoint_scope_repair:
        context=frozen['viewpoint_scope_context']
        for b in [manifest.viewpoint_scope_repair,context['policy'],*context['reports']]:
            bound_bytes(b,frozen['physical_snapshots'] if historical else None)
    if manifest.deferred_repair:
        for b in (manifest.deferred_repair.investigation_packet, manifest.deferred_repair.handoff,
                  manifest.deferred_repair.raw_gpt, manifest.deferred_repair.raw_opus):
            bound_bytes(b, frozen["physical_snapshots"] if historical else None)
        if manifest.deferred_repair.provider_schema_rejection:
            bound_bytes(manifest.deferred_repair.provider_schema_rejection, frozen["physical_snapshots"] if historical else None)


def _semantic(row: dict) -> dict:
    return {k: v for k, v in row.items() if k not in PROVENANCE | {"revision"}}


def validate_proposal(frozen: dict, proposal: Proposal, *, review_only: bool = False, claim_first: bool = False, initial_claim_draft: bool = False) -> dict[str, dict]:
    before = index(frozen["before_records"])
    manifest = Manifest.model_validate(frozen["manifest"])
    allowed = {p.key: p for p in manifest.permissions}
    proposed = index(proposal.records)
    for k, payload in proposed.items():
        if k in before or k in allowed:
            continue
        collection, _ = split_key(k)
        parent_field = "source_id" if collection == "source_fragments" else "viewpoint_id" if collection == "viewpoint_revisions" else None
        matches = [p for p in manifest.permissions if p.create and p.collection == collection
                   and p.parent_id and payload.get(parent_field) == p.parent_id]
        if len(matches) == 1:
            allowed[k] = matches[0]
    dispositions = {d.record_key: d for d in proposal.dispositions}
    required = set(frozen["inventory"]["affected_keys"]) | set(proposed)
    if len(dispositions) != len(proposal.dispositions) or set(dispositions) != required:
        raise ValueError("every affected consumer requires exactly one disposition")
    unresolved = {d.record_key for d in proposal.dispositions if d.action == 'unresolved'}
    if initial_claim_draft:
        # An initial draft is not a write authority. Permit only unchanged,
        # current SQL-pinned dependencies to remain pending for the original
        # independent review and unique correction. Unknown/source/hold failures
        # and all permission, identity and epoch gates still apply below.
        if (not manifest.claim_issue or not frozen.get('claim_issue_context')
                or not frozen.get('sql_scope') or claim_first or review_only):
            raise ValueError('initial Claim draft requires exact SQL Claim management context')
        pins = {(r['collection'], r['object_id']): r['pin'] for r in frozen['sql_scope']['read_pins']}
        for k in unresolved:
            col, ident = split_key(k)
            old = before.get(k)
            pin = pins.get((col, ident))
            readonly_source_dependency = col in {'evidence_steps', 'knowledge_relations'}
            if (col not in {'viewpoint_claim_links', 'canonical_viewpoints', 'viewpoint_revisions',
                            'evidence_steps', 'knowledge_relations'}
                    or old is None or k in proposed or pin != [old.get('revision', 1),
                        sha256_json({f:v for f,v in old.items() if f != 'revision'}), False]
                    or old.get('review_status') in HUMAN_HOLDS | {'human_hold', 'rejected', 'withheld_unreviewed'}
                    or (readonly_source_dependency and k in allowed)):
                raise ValueError('initial Claim draft pending dependency is foreign/stale/held/writable')
        if any(a.cause == 'source_unresolved' for a in proposal.claim_assessments):
            raise ValueError('source/attribution uncertainty needs content owner')
    if claim_first:
        from backend.pipeline.claim_first_management import SOURCE_COLUMNS, CVP_COLUMNS
        pending = {k for k in required if split_key(k)[0] in CVP_COLUMNS}
        if (not manifest.claim_issue or unresolved != pending
                or any(split_key(k)[0] not in SOURCE_COLUMNS for k in proposed)):
            raise ValueError('Claim-first must defer every CVP and write only source-owned records')
        review_only = True
    pending_link_keys=set()
    if review_only and frozen.get('owner_claim_completion'):
        from backend.pipeline.claim_owner_revision import partial_review
        pending_link_keys=set(partial_review(frozen,proposal)['pending_link_keys'])
    elif review_only and (not frozen.get('claim_issue_context', {}).get('scope_amendment')
            or (not claim_first and not any(row['pin'][2] is True for row in frozen.get('sql_scope', {}).get('read_pins', [])))
            or any(split_key(k)[0] not in {'canonical_viewpoints', 'viewpoint_revisions'}
                   and not (claim_first and split_key(k)[0] in CVP_COLUMNS)
                   or k not in before or k in proposed for k in unresolved)):
        raise ValueError('unresolved review requires bounded unchanged CVP context and SQL retirement proof')
    if unresolved_consumers(frozen) or (unresolved and not review_only and not initial_claim_draft):
        raise ValueError("unknown/unresolved consumer; owner scope or proof required")
    historical_scope=set()
    if frozen.get('viewpoint_scope_context'):
        from backend.pipeline.cvp_scope_management import historical_impact_keys
        historical_scope=historical_impact_keys(frozen)
    for k, d in dispositions.items():
        c, _ = split_key(k)
        if (review_only or initial_claim_draft) and k in unresolved:
            continue  # Review a retained unresolved object, never authorize a write.
        if c in IMPACT_ONLY or (c == 'knowledge_routes' and k in frozen['inventory']['unknown_keys']):
            if d.action != "impact_only" or k in proposed:
                raise ValueError("historical/output consumers may only be invalidated, not regenerated")
        elif k in historical_scope and d.action=='impact_only':
            if k in proposed or k in allowed:
                raise ValueError('historical scope context cannot be proposed or writable: '+k)
        elif d.action == "update":
            if k not in proposed or k not in allowed:
                raise ValueError("update outside exact permission: " + k)
        elif d.action != "retain" or k in proposed:
            raise ValueError("retain must keep the exact record: " + k)
    post = deepcopy(before)
    for k, new in proposed.items():
        permission = allowed.get(k)
        if permission is None:
            raise ValueError("unapproved write: " + k)
        old = before.get(k)
        c, object_id = split_key(k)
        id_field = KNOWLEDGE_COLLECTIONS[c][1]
        if new[id_field] != object_id:
            raise ValueError("identity drift")
        changed_fields = {f for f in set(old or {}) | set(new) if (old or {}).get(f) != new.get(f)}
        if changed_fields - set(permission.fields) - {"revision", id_field} - PROVENANCE:
            raise ValueError("field change outside permission: " + k)
        if old and c == 'claims' and 'occurrences' in changed_fields:
            from backend.pipeline.claim_retained_occurrence_context import validate_occurrence_delta
            validate_occurrence_delta(frozen, object_id, old, new)
        if old and old.get("review_status") in HUMAN_HOLDS and new != old:
            from backend.pipeline.cvp_scope_management import approved_relation_reference_only
            if not approved_relation_reference_only(frozen,k,proposed):
                raise ValueError("existing human hold/ruling needs an exact separate owner disposition")
        if new.get("review_status", "candidate") != "candidate":
            raise ValueError("proposal may not inherit or manufacture approval: " + k)
        if new.get("revision") != (old.get("revision", 1) + 1 if old else 1):
            raise ValueError("proposed version is not the next stored revision")
        if old and _semantic(new) == _semantic(old):
            raise ValueError("unchanged record must be retained, not assigned a draft-only revision")
        post[k] = deepcopy(new)
    creation_parents = [p.parent_id for p in manifest.permissions if p.create and p.collection == "viewpoint_revisions" and p.parent_id]
    for parent in creation_parents:
        if sum(split_key(k)[0] == "viewpoint_revisions" and p.get("viewpoint_id") == parent and k not in before for k, p in proposed.items()) > 1:
            raise ValueError("one source migration may create only one current revision per CVP")
    source_key = key("source_documents", manifest.source_id)
    doc = post[source_key]
    target = frozen["after"][0]
    if (doc.get("source_body_sha256") != target["body_sha256"] or doc.get("source_sha256") != target["body_sha256"]
            or doc.get("source_file_sha256") != target["file"]["file_sha256"]
            or doc.get("source_path") != target["file"]["path"]):
        raise ValueError("source epoch was not migrated to the exact current source")
    if any(doc.get(f) != before[source_key].get(f) for f in ("source_id", "source_type", "transcript_id", "canonical_source_id", "locator_space")):
        raise ValueError("source migration cannot change the registered source identity")
    if {split_key(k)[1] for k in before if k.startswith("claims/")} != {split_key(k)[1] for k in post if k.startswith("claims/")}:
        raise ValueError("source update cannot silently change Claim membership")
    if initial_claim_draft:
        return post  # Review-only: graph/coverage findings are disclosed, never waived for final/write.
    validate_graph(post, before, frozen, pending_link_keys=pending_link_keys)
    if manifest.deferred_repair:
        from backend.pipeline.deferred_claim_repair import validate_postimages
        validate_postimages(frozen, post)
    if manifest.claim_issue:
        from backend.pipeline.claim_issue_management import validate_resolution
        validate_resolution(frozen, proposal, post, review_only=review_only)
    if manifest.viewpoint_scope_repair:
        from backend.pipeline.cvp_scope_management import validate_postimages
        validate_postimages(frozen, proposal, post)
    sentence_ids = [d.sentence_id for d in proposal.sentence_dispositions]
    if len(sentence_ids) != len(set(sentence_ids)) or set(sentence_ids) != {s["sentence_id"] for s in frozen["sentence_inventory"]}:
        raise ValueError("authorized source sentence denominator incomplete or duplicated")
    candidates, candidate_ids = defaultdict(list), set()
    for candidate in proposal.unadmitted_candidates:
        cid = candidate.get("candidate_id")
        covered = candidate.get("sentence_ids", [])
        citations = candidate.get("citations", [])
        if (not isinstance(cid, str) or not cid or cid in candidate_ids or not candidate.get("statement")
                or candidate.get("source_id") != manifest.source_id or not covered or len(covered) != len(set(covered))
                or not set(covered) <= set(sentence_ids) or not citations):
            raise ValueError("independent candidate requires unique identity and exact own-source sentence coverage")
        candidate_ids.add(cid)
        for citation in citations:
            text = target["paragraphs"].get(citation.get("paragraph_key"), {}).get("text", "")
            quote = citation.get("verbatim_excerpt")
            if citation.get("paragraph_key") not in manifest.authorized_paragraph_keys or not quote or text.count(quote) != 1:
                raise ValueError("independent candidate citation is missing/ambiguous/outside authorized source")
        for sid in covered:
            candidates[sid].append(cid)
    for d in proposal.sentence_dispositions:
        if d.action == "unresolved" or any(k not in post for k in d.record_keys):
            raise ValueError("source sentence has an unresolved or missing record disposition")
        if d.action == "represented" and not d.record_keys:
            raise ValueError("represented sentence requires concrete record references")
        if d.action == "unadmitted_candidate" and not candidates[d.sentence_id]:
            raise ValueError("uncovered judgment must retain its independent candidate")
        if candidates[d.sentence_id] and d.action != "unadmitted_candidate":
            raise ValueError("independent candidate sentence disposition must remain explicitly unadmitted")
    return post


def retained_evidence_sequence_start(frozen, before, post, claim_key, evidence_key, fragment, text):
    """An exact unique full Evidence sequence can disambiguate its short quote.

    Only unchanged current SQL-pinned chains on an unchanged source qualify.
    No first-occurrence choice, new Evidence, qualification change or inferred
    gap/order is permitted. All quotes must already be bound to THIS Evidence.
    """
    if frozen['manifest']['before_source'] != frozen['manifest']['current_sources'][0]:
        raise ValueError('retained Evidence sequence requires unchanged physical source')
    evidence = post[evidence_key]
    ids = evidence.get('source_fragment_ids') or ([evidence['source_fragment_id']]
                                                if evidence.get('source_fragment_id') else [])
    if (len(ids) < 2 or len(ids) != len(set(ids))
            or evidence.get('source_fragment_id') not in {None, *ids}):
        raise ValueError('retained Evidence sequence requires distinct ordered bound fragments')
    keys = [key('source_fragments', fid) for fid in ids]
    pins = {(row['collection'], row['object_id']): row['pin']
            for row in frozen.get('sql_scope', {}).get('read_pins', [])}
    for k in [claim_key, evidence_key, *keys]:
        pin = pins.get(split_key(k))
        if (not pin or pin[2] is not False or before.get(k) != post.get(k)
                or pin[0] != before[k].get('revision') or pin[1] != record_content_sha(before[k])):
            raise ValueError('retained Evidence sequence current SQL chain changed/missing/retired')
    source_id = frozen['manifest']['source_id']
    evidence_id = split_key(evidence_key)[1]
    claim_id = split_key(claim_key)[1]
    if (evidence_id not in post[claim_key].get('evidence_step_ids', [])
            or claim_id not in evidence.get('produced_claim_ids', [])
            or any(post[k].get('review_status') in HUMAN_HOLDS | {'human_hold', 'withheld_unreviewed', 'rejected'}
                   for k in [claim_key, evidence_key, *keys])):
        raise ValueError('retained Evidence sequence ownership/hold conflict')
    quotes = []
    for k in keys:
        value = post[k]
        quote = value.get('verbatim_excerpt')
        if (not quote or value.get('source_id') != source_id
                or value.get('paragraph_key') != fragment['paragraph_key']
                or value.get('source_sha256') != frozen['after'][0]['body_sha256']
                or value.get('paragraph_text_sha256') != hashlib.sha256(text.encode()).hexdigest()
                or value.get('verbatim_excerpt_sha256') != hashlib.sha256(quote.encode()).hexdigest()
                or value.get('anchor_state') != 'source_version_bound'):
            raise ValueError('retained Evidence sequence exact own source/quote hash drift')
        quotes.append(quote)
    full = ''.join(quotes)
    if text.count(full) != 1 or fragment['fragment_id'] not in ids:
        raise ValueError('complete bound Evidence sequence absent/ambiguous')
    position = ids.index(fragment['fragment_id'])
    return text.index(full) + sum(len(q) for q in quotes[:position])


def anchor_evidence_id(claim, occurrence, anchor):
    """Resolve a declared local ID, never infer one from spelling or position."""
    eid = anchor.get('evidence_id')
    owned = claim.get('evidence_step_ids', [])
    if eid in owned:
        return eid
    local = occurrence.get('local_source_evidence_ids', [])
    canonical = occurrence.get('canonical_evidence_step_ids', [])
    if (len(local) != len(canonical) or len(local) != len(set(local))
            or len(canonical) != len(set(canonical)) or eid not in local
            or not set(canonical) <= set(owned)):
        raise ValueError('anchor is not owned by a Claim Evidence step')
    return canonical[local.index(eid)]


def containing_anchor_fragments(fragments, quote, text, source_id, paragraph_key, body_sha):
    """A unique exact quote may be inside its own reviewed continuous excerpt."""
    result = []
    for fragment in fragments:
        excerpt = fragment.get('verbatim_excerpt', '')
        if (not quote or not excerpt or fragment.get('source_id') != source_id
                or fragment.get('paragraph_key') != paragraph_key
                or fragment.get('source_sha256') != body_sha
                or fragment.get('anchor_state') != 'source_version_bound'
                or fragment.get('paragraph_text_sha256') != hashlib.sha256(text.encode()).hexdigest()
                or fragment.get('verbatim_excerpt_sha256') != hashlib.sha256(excerpt.encode()).hexdigest()
                or text.count(excerpt) != 1 or text.count(quote) != 1 or excerpt.count(quote) != 1):
            continue
        result.append(fragment)
    return result


def validate_graph(post: dict[str, dict], before: dict[str, dict], frozen: dict, *, pending_link_keys=()) -> None:
    """Mechanical checks over the entire affected graph, not just write rows."""
    source_id = frozen["manifest"]["source_id"]
    paragraphs = frozen["after"][0]["paragraphs"]
    body_sha = frozen["after"][0]["body_sha256"]
    all_paragraphs = {source_id: paragraphs, **{s["source_id"]: s["paragraphs"] for s in frozen.get("context_sources", [])}}
    own_doc = post[key("source_documents", source_id)]
    aliases = {own_doc.get("transcript_id"), source_id, own_doc.get("canonical_source_id")} - {None, ""}
    for k in sorted(set(frozen["inventory"]["affected_keys"]) | (set(post) - set(before))):
        p = post[k]
        c, object_id = split_key(k)
        if c == "source_fragments" and p.get("source_id") == source_id:
            quote = p.get("verbatim_excerpt", "")
            text = paragraphs.get(str(p.get("paragraph_key")), {}).get("text", "")
            if not quote or text.count(quote) != 1 or p.get("source_sha256") != body_sha:
                raise ValueError("quote must resolve uniquely in its own new-source paragraph: " + k)
            for name, actual in (("paragraph_text_sha256", text), ("verbatim_excerpt_sha256", quote)):
                if p.get(name) and p[name] != hashlib.sha256(actual.encode("utf-8")).hexdigest():
                    raise ValueError("exact paragraph/excerpt hash drift: " + k)
        if c == "evidence_steps":
            for fid in set(p.get("source_fragment_ids", [])) | ({p["source_fragment_id"]} if p.get("source_fragment_id") else set()):
                if key("source_fragments", fid) not in post:
                    raise ValueError("dangling Evidence fragment")
            for cid in p.get("produced_claim_ids", []):
                if object_id not in post[key("claims", cid)].get("evidence_step_ids", []):
                    raise ValueError("Evidence reverse pointer is not reciprocal")
        if c == "claims":
            for eid in p.get("evidence_step_ids", []):
                evidence = post.get(key("evidence_steps", eid))
                if not evidence or object_id not in evidence.get("produced_claim_ids", []):
                    raise ValueError("Claim Evidence chain is not reciprocal")
            # Duplicate/overlapping anchors must share a basis with one representative.
            spans = []
            for occurrence in p.get("occurrences", []):
                if not aliases.intersection(set(strings(occurrence))):
                    continue
                for anchor in occurrence.get("anchors", []):
                    current_anchor_profile = frozen.get('claim_issue_context', {}).get(
                        'anchor_binding_validation_profile') == 'declared_local_own_containing_v1'
                    eid = (anchor_evidence_id(p, occurrence, anchor) if current_anchor_profile
                           else anchor.get('evidence_id'))
                    if eid not in p.get("evidence_step_ids", []):
                        raise ValueError("anchor is not owned by a Claim Evidence step")
                    evidence = post[key("evidence_steps", eid)]
                    fids = set(evidence.get("source_fragment_ids", [])) | ({evidence["source_fragment_id"]} if evidence.get("source_fragment_id") else set())
                    text = paragraphs.get(str(anchor.get("paragraph_key")), {}).get("text", "")
                    highlight = anchor.get("proposed_highlight", {})
                    quote = highlight.get("text") if isinstance(highlight, dict) else highlight
                    matches = [post[key("source_fragments", fid)] for fid in fids
                               if post[key("source_fragments", fid)].get("source_id") == source_id
                               and post[key("source_fragments", fid)].get("paragraph_key") == anchor.get("paragraph_key")
                               and post[key("source_fragments", fid)].get("verbatim_excerpt") == quote]
                    if not matches and current_anchor_profile:
                        matches = containing_anchor_fragments(
                            [post[key('source_fragments', fid)] for fid in fids], quote, text,
                            source_id, anchor.get('paragraph_key'), body_sha)
                    if not quote or text.count(quote) < 1 or len(matches) != 1:
                        raise ValueError("anchor -> Evidence -> exact own fragment chain missing/ambiguous")
                    start = (text.index(quote) if text.count(quote) == 1 else
                             retained_evidence_sequence_start(frozen, before, post, k,
                                                             key('evidence_steps', eid), matches[0], text))
                    spans.append((anchor["paragraph_key"], start, start + len(quote), anchor))
            validate_basis_groups(spans)
        if c == "viewpoint_claim_links":
            if k in pending_link_keys:
                if p!=before[k]:raise ValueError('incomplete review cannot change a pending connection')
                claim=before[key("claims",p["claim_id"])]
            else:
                claim = post[key("claims", p["claim_id"])]
            viewpoint = post[key("canonical_viewpoints", p["viewpoint_id"])]
            if (p.get("effective_state", "active") == "active"
                    and p["validated_against_viewpoint_revision_id"] != viewpoint["current_revision_id"]):
                raise ValueError("active link must be reviewed against the current CVP revision")
            if p["pinned_claim_revision"] != claim["revision"]:
                raise ValueError("link pins the old Claim version")
            loc = p.get("component_locator")
            if loc:
                # Pending provenance will be rebound by the deterministic compiler.
                if loc.get("claim_sha256") != semantic_record_sha(claim):
                    raise ValueError("locator is not bound to the proposed Claim")
                for span in loc.get("canonical_spans", []):
                    if claim["statement"][span["start_char"]:span["end_char"]] != span["exact_text"]:
                        raise ValueError("component locator dropped or changed subject text")
            for b in p.get("evidence_bindings", []):
                evidence = post.get(key("evidence_steps", b.get("evidence_step_id", "")))
                fragment = post.get(key("source_fragments", b.get("source_fragment_id", "")))
                if not evidence or not fragment:
                    raise ValueError("link has dangling evidence binding")
                if b["source_fragment_id"] not in set(evidence.get("source_fragment_ids", [])) | {evidence.get("source_fragment_id")}:
                    raise ValueError("link still uses a removed Evidence fragment")
            binding_spans = []
            for b in p.get("evidence_bindings", []):
                fragment = post[key("source_fragments", b["source_fragment_id"])]
                sid, para, quote = fragment["source_id"], fragment["paragraph_key"], fragment["verbatim_excerpt"]
                text = all_paragraphs.get(sid, {}).get(para, {}).get("text", "")
                if text.count(quote) != 1:
                    raise ValueError("link binding source context absent/ambiguous")
                start = text.index(quote)
                if any(s == sid and pkey == para and start < end and low < start + len(quote) for s, pkey, low, end in binding_spans):
                    raise ValueError("link bindings cannot count duplicate/overlapping source evidence")
                binding_spans.append((sid, para, start, start + len(quote)))
        if c == "canonical_viewpoints":
            revision = post.get(key("viewpoint_revisions", p["current_revision_id"]))
            if not revision or revision["viewpoint_id"] != object_id:
                raise ValueError("CVP revision belongs to another identity")
            old = before[k]
            if p["current_revision_id"] != old["current_revision_id"]:
                if revision.get("supersedes_revision_id") != old["current_revision_id"]:
                    raise ValueError("new CVP revision must preserve the supersedes chain")
                if key("viewpoint_revisions", old["current_revision_id"]) not in post:
                    raise ValueError("old CVP revision must remain")


def validate_basis_groups(spans: list[tuple]) -> None:
    """Connected overlapping anchors must count as exactly one evidence basis."""
    remaining = set(range(len(spans)))
    while remaining:
        group = {min(remaining)}
        queue = list(group)
        while queue:
            i = queue.pop()
            para, low, high, _ = spans[i]
            for j in remaining - group:
                p, l, h, _ = spans[j]
                if para == p and low < h and l < high:
                    group.add(j)
                    queue.append(j)
        remaining -= group
        if len(group) < 2:
            continue
        flags = [spans[i][3].get("evidence_independence", {}) for i in sorted(group)]
        ids = {f.get("basis_group_id") for f in flags}
        if (len(ids) != 1 or None in ids or "" in ids
                or any(f.get("count_once_per_basis_group") is not True for f in flags)
                or sum(f.get("is_basis_representative") is True for f in flags) != 1):
            raise ValueError("overlapping anchors require one basis group and exactly one representative")


def review_packet(frozen: dict, proposal: Proposal, *, review_only: bool = False, claim_first: bool = False, initial_claim_draft: bool = False) -> dict:
    post = validate_proposal(frozen, proposal, review_only=review_only, claim_first=claim_first,
                      initial_claim_draft=initial_claim_draft)
    selected = frozen["inventory"]["affected_keys"] + frozen["inventory"]["context_keys"]
    before = index(frozen["before_records"])
    result = {
        "schema_version": VERSION, "update_id": frozen["update_id"],
        "manifest": frozen["manifest"], "before_source": frozen["before"], "current_sources": frozen["after"],
        "context_sources": frozen.get("context_sources", []),
        "sentence_inventory": frozen["sentence_inventory"],
        "inventory": frozen["inventory"], "before_records": rows({k: before[k] for k in selected}),
        **({"deferred_diagnosis": frozen["deferred_diagnosis"]} if "deferred_diagnosis" in frozen else {}),
        **({"claim_issue_context": frozen["claim_issue_context"]} if "claim_issue_context" in frozen else {}),
        **({'viewpoint_scope_context': frozen['viewpoint_scope_context']} if 'viewpoint_scope_context' in frozen else {}),
        "proposal": proposal.model_dump(), "proposal_sha256": sha256_json(proposal.model_dump()),
        "provenance_contract": {
            "old_approval_is_history_only": True, "reviewer": "claude-opus-5-5",
            "approval_basis": "owner_scoped_independent_terminal_review",
            "deterministic_after_review_changes": ["fresh review fields", "fresh candidate/decision IDs", "dependent final Claim SHA"],
            "new_revision_objects_start_at_one": True, "correction_limit": 1,
            **({"deterministic_before_review": ["exact source/paragraph/quote SHA", "new quote source_version_bound",
                "Claim schema defaults", "connected-overlap one-basis metadata", "proposed Claim locator SHA",
                "explicit new quote create disposition", "read-only CVP impact token becomes exact retain",
                "verified redundant Evidence buckets retain old Claim storage shape"]}
               if frozen["manifest"].get("deferred_repair") else {}),
        },
    }
    if frozen.get('claim_issue_context',{}).get('complete_input_repair'):
        from backend.pipeline.claim_citation_purpose_review import receipt
        value=receipt(frozen,proposal,post)
        if value:result['claim_citation_purpose_review']=value
    if initial_claim_draft:
        findings = []
        try:
            validate_proposal(frozen, proposal)
        except ValueError as exc:
            findings.append(str(exc))
        post = validate_proposal(frozen, proposal, initial_claim_draft=True)
        try:
            validate_graph(post, before, frozen)
        except ValueError as exc:
            findings.append(str(exc))
        if frozen['manifest'].get('claim_issue'):
            from backend.pipeline.claim_issue_management import validate_resolution
            try:
                validate_resolution(frozen, proposal, post)
            except ValueError as exc:
                findings.append(str(exc))
        result['unresolved_proposal_review'] = {
            'schema_version': 'claim_initial_draft_review.v1',
            'pending_record_keys': sorted(d.record_key for d in proposal.dispositions if d.action == 'unresolved'),
            'program_findings': findings,
            'content_write_authority': False,
            'mandatory_original_unique_correction': True,
            'explanation': 'This is the original initial draft, not an approved afterimage. '
                'Review the complete proposal, own sources and all dependencies. Report every graph, '
                'binding and coverage defect in this same independent review. Pending existing rows '
                'are unchanged, not approved for revision. The proposer must use its original single '
                'correction to resolve all findings within the existing permissions; no permission '
                'is expanded and strict final validation and independent review remain mandatory.'}
    elif claim_first:
        from backend.pipeline.claim_first_management import CVP_COLUMNS, VERSION as CLAIM_FIRST_VERSION
        result['source_first_pending_cvp'] = {
            'schema_version': CLAIM_FIRST_VERSION,
            'pending_record_keys': sorted(d.record_key for d in proposal.dispositions
                                         if split_key(d.record_key)[0] in CVP_COLUMNS),
            'source_only_write': True, 'cvp_content_approved': False,
            'group_completion_blocked': True}
    elif review_only:
        result['unresolved_proposal_review'] = {
            'schema_version': 'source_unresolved_retirement_context_review.v1',
            'retired_current_sql_pins': [row for row in frozen['sql_scope']['read_pins'] if row['pin'][2] is True],
            'explanation': 'These exact SQL-pinned objects are retired, not missing active members. '
                'Historical creation decisions do not establish current membership. Read-only current '
                'Claims do not replace historical identities or approve a new identity mapping. '
                'Review the unchanged unresolved proposal and complete afterstates independently; '
                'unresolved items cannot be approved or committed. A genuine disagreement uses only '
                'the existing single correction, then a strict complete final review.',
            'write_authority': False,
        }
        if frozen.get('owner_claim_completion'):
            from backend.pipeline.claim_owner_revision import partial_review
            result['unresolved_proposal_review']=partial_review(frozen,proposal)
    return result


def validate_review(packet: dict, response: dict) -> bool:
    from backend.api.canonical_repository.viewpoint_response_binding import bind_response
    review = Review.model_validate(bind_response(Review,response,packet))
    required = {d["record_key"] for d in packet["proposal"]["dispositions"]}
    if packet.get('claim_citation_purpose_review'):
        from backend.pipeline.claim_citation_purpose_review import VERSION
        value=packet['claim_citation_purpose_review']
        if (value.get('schema_version')!=VERSION or value.get('automatic_content_approval') is not False
                or not packet.get('claim_issue_context',{}).get('complete_input_repair')):
            raise ValueError('citation purpose review authority drift')
        extra=[v['record_key'] for v in value['items']]
        if len(set(extra))!=len(extra) or set(extra)&required:raise ValueError('citation purpose denominator drift')
        required.update(extra)
    actual = [v.record_key for v in review.verdicts]
    if (review.proposal_sha256 != packet["proposal_sha256"] or len(actual) != len(set(actual)) or set(actual) != required):
        raise ValueError("review did not cover the exact complete consumer denominator")
    if any(v.approved and v.problems for v in review.verdicts):
        raise ValueError("pass with problems is not an approval")
    if packet.get('source_first_pending_cvp'):
        from backend.pipeline.claim_first_management import PENDING_PROBLEM
        pending = set(packet['source_first_pending_cvp']['pending_record_keys'])
        return all((not v.approved and v.problems == [PENDING_PROBLEM] and bool(v.reason))
                   if v.record_key in pending else (v.approved and not v.problems)
                   for v in review.verdicts)
    return (not packet.get('unresolved_proposal_review')
            and all(v.approved and not v.problems for v in review.verdicts))


def compile_package(frozen: dict, proposal: Proposal, raw: dict, *, frozen_sha256: str | None = None, claim_first: bool = False, provenance_templates: dict | None = None) -> dict:
    """Only declared deterministic provenance changes after actual Opus approval."""
    packet = review_packet(frozen, proposal, claim_first=claim_first)
    if not validate_review(packet, raw["response"]):
        raise ValueError("partial/rejected review cannot authorize a package")
    before = index(frozen["before_records"])
    # Missing forward candidate templates are not additional semantic input.
    # The SQL caller authenticates their exact committed history and pins them
    # in the write transaction; the reviewer packet stays byte-for-byte bound.
    if provenance_templates:
        if not frozen['manifest'].get('viewpoint_scope_repair'):
            raise ValueError('extra provenance templates require scope management')
        required = {key('viewpoint_identity_candidates', before[key('viewpoint_identity_decisions',
                    before[k]['decision_id'])]['identity_candidate_id'])
                    for k in index(proposal.records) if k.startswith('viewpoint_claim_links/')}
        if set(provenance_templates) - required:
            raise ValueError('foreign scope provenance template')
        for k, value in provenance_templates.items():
            if k in before and before[k] != value:
                raise ValueError('scope provenance template drift')
            before[k] = deepcopy(value)
    # A completed consumer may supply the authenticated original full-freeze
    # seal while reading only the exact original reviewer readset. IDs must not
    # change merely because unrelated predecessor rows were not materialized.
    if frozen_sha256 is not None and (not isinstance(frozen_sha256,str)
            or len(frozen_sha256)!=64 or any(ch not in '0123456789abcdef' for ch in frozen_sha256)):
        raise ValueError('exact original frozen SHA required')
    frozen_identity = frozen_sha256 or sha256_json(frozen)
    data = index(proposal.records)
    digest = raw["artifact_sha256"]
    reviewed_at = raw["completed_at"]
    identity_by_viewpoint = defaultdict(list)
    for k, p in data.items():
        if split_key(k)[0] in {"claims", "evidence_steps", "source_documents", "source_fragments",
                               "observations", "questions", "position_nodes", "knowledge_relations", "claim_relations"}:
            p.update(review_status="independent_terminal_reviewed", reviewed_by="claude-opus-5-5",
                     reviewed_at=reviewed_at,
                     review_note="New source reconciliation; exact Opus review, not human approval or GPT preapproval.",
                     source_reconciliation_review_sha256=digest)
        elif split_key(k)[0] in {"canonical_viewpoints", "viewpoint_revisions", "viewpoint_claim_links", "viewpoint_relations"}:
            p["review_status"] = "system_approved"
    # Normalize Claim defaults BEFORE computing the final dependent locator SHA.
    for k, p in list(data.items()):
        if k.startswith("claims/"):
            data[k] = KNOWLEDGE_COLLECTIONS["claims"][0].model_validate(p).model_dump(mode="json")
    claims = {k: p for k, p in {**before, **data}.items() if k.startswith("claims/")}
    for k, link in list(data.items()):
        if not k.startswith("viewpoint_claim_links/"):
            continue
        previous = before[key("viewpoint_identity_decisions", before[k]["decision_id"])]
        candidate = deepcopy(before[key("viewpoint_identity_candidates", previous["identity_candidate_id"])])
        seed = sha256_json({"version": VERSION, "update": frozen["update_id"], "review": digest, "link": k})
        candidate.update(revision=1, candidate_claim_ids=[link["claim_id"]], candidate_viewpoint_ids=[link["viewpoint_id"]],
                         proposed_action="match_existing", generation_fingerprint=seed, coverage_snapshot_id=None,
            scope_manifest_sha256=frozen_identity, blocker_codes=[], seed_relation_ids=[])
        identity = {"claims": candidate["candidate_claim_ids"], "viewpoints": candidate["candidate_viewpoint_ids"],
                    "relations": candidate.get("seed_relation_ids", []), "action": candidate["proposed_action"],
                    "blockers": candidate.get("blocker_codes", []), "coverage_snapshot_id": candidate.get("coverage_snapshot_id"),
                    "generation_fingerprint": seed}
        if candidate.get("scope_manifest_sha256"):
            identity["scope_manifest_sha256"] = candidate["scope_manifest_sha256"]
        candidate["identity_candidate_id"] = "VIC-" + sha256_json(identity)[:20]
        decision = deepcopy(previous)
        decision.update(revision=1, identity_decision_id="VID-" + seed[:20], identity_candidate_id=candidate["identity_candidate_id"],
                        decision="match_existing", proposition_unit_link_decisions=[],
                        input_sha256=seed, claim_link_decisions=[{"claim_id": link["claim_id"], "link_type": link["link_type"]}],
                        resolved_viewpoint_id=link["viewpoint_id"], review_artifact_sha256=digest,
                        semantic_call_artifact_sha256s=[digest], reviewer_model_ids=["claude-opus-5-5"],
                        reviewer_kind="system", reviewer_id=REVIEWER, policy_version=VERSION,
                        approval_basis="owner_scoped_independent_terminal_review", review_status="system_approved",
                        created_at=reviewed_at, reason="Exact independent source-reconciliation review.")
        link["decision_id"] = decision["identity_decision_id"]
        if link.get("component_locator"):
            link["component_locator"]["claim_sha256"] = semantic_record_sha(claims[key("claims", link["claim_id"])])
        data[key("viewpoint_identity_candidates", candidate["identity_candidate_id"])] = candidate
        data[key("viewpoint_identity_decisions", decision["identity_decision_id"])] = decision
        identity_by_viewpoint[link["viewpoint_id"]].append(decision["identity_decision_id"])
    for k, revision in list(data.items()):
        if not k.startswith("viewpoint_revisions/"):
            continue
        vid = revision["viewpoint_id"]
        ids = identity_by_viewpoint[vid]
        if not ids:
            # A CVP text revision may not inherit its old approval when no
            # link needed changing. Build one fresh identity decision from
            # the full current member denominator supplied to the reviewer.
            old_view = before[key("canonical_viewpoints", vid)]
            old_revision = before[key("viewpoint_revisions", old_view["current_revision_id"])]
            previous = before[key("viewpoint_identity_decisions", old_revision["provenance"]["basis_identity_decision_ids"][0])]
            candidate = deepcopy(before[key("viewpoint_identity_candidates", previous["identity_candidate_id"])])
            member_ids = sorted({p["claim_id"] for rk, p in {**before, **data}.items()
                if rk.startswith("viewpoint_claim_links/") and p["viewpoint_id"] == vid
                and p.get("effective_state", "active") == "active" and p["link_type"].startswith("equivalent_")})
            if not member_ids:
                raise ValueError("CVP text revision has no complete active member evidence")
            seed = sha256_json({"version": VERSION, "update": frozen["update_id"], "review": digest, "revision": k})
            candidate.update(revision=1, candidate_claim_ids=member_ids, candidate_viewpoint_ids=[vid], proposed_action="match_existing",
                generation_fingerprint=seed, coverage_snapshot_id=None, scope_manifest_sha256=frozen_identity, blocker_codes=[], seed_relation_ids=[])
            identity = {"claims": member_ids, "viewpoints": [vid], "relations": candidate.get("seed_relation_ids", []),
                "action": "match_existing", "blockers": candidate.get("blocker_codes", []),
                "coverage_snapshot_id": candidate.get("coverage_snapshot_id"), "generation_fingerprint": seed}
            if candidate.get("scope_manifest_sha256"):
                identity["scope_manifest_sha256"] = candidate["scope_manifest_sha256"]
            candidate["identity_candidate_id"] = "VIC-" + sha256_json(identity)[:20]
            decision = deepcopy(previous)
            decision.update(revision=1, identity_decision_id="VID-" + seed[:20], identity_candidate_id=candidate["identity_candidate_id"],
                decision="match_existing", resolved_viewpoint_id=vid, claim_link_decisions=[], proposition_unit_link_decisions=[],
                input_sha256=seed, review_artifact_sha256=digest, semantic_call_artifact_sha256s=[digest],
                reviewer_model_ids=["claude-opus-5-5"], reviewer_kind="system", reviewer_id=REVIEWER,
                policy_version=VERSION, approval_basis="owner_scoped_independent_terminal_review", review_status="system_approved",
                created_at=reviewed_at, reason="Full-member CVP revision approved by this independent Opus review.")
            data[key("viewpoint_identity_candidates", candidate["identity_candidate_id"])] = candidate
            data[key("viewpoint_identity_decisions", decision["identity_decision_id"])] = decision
            ids = [decision["identity_decision_id"]]
        revision.update(provenance={"basis_identity_decision_ids": sorted(ids), "review_artifact_sha256": digest},
                        approved_by="claude-opus-5-5", approved_at=reviewed_at)
    if frozen['manifest'].get('viewpoint_scope_repair'):
        for k, relation in data.items():
            if k.startswith('viewpoint_relations/'):
                vids={relation['source_viewpoint_id'],relation['target_viewpoint_id']}
                relation['review_provenance']={
                    'basis_identity_decision_ids':sorted({d for vid in vids for d in identity_by_viewpoint[vid]}),
                    'review_artifact_sha256':digest}
    body = {"package_id": frozen["update_id"]}
    for k, p in sorted(data.items()):
        body.setdefault(split_key(k)[0], []).append(p)
    # Shape/default normalization is part of the store contract, not a semantic rewrite.
    normalized = normalize_package(body)
    return {"package_id": body["package_id"], **{c: list(by_id.values()) for c, by_id in normalized.items() if by_id}}


def assert_plan_postimages(package: dict, plan: dict, before: dict[str, dict]) -> dict[str, dict]:
    normalized, stated = _normalize_records(package)
    # Mirror the store's explicit-field merge. New schema defaults must never
    # turn omitted historical fields into unreviewed null/empty writes.
    expected={}
    for collection,records in normalized.items():
        for oid,payload in records.items():
            k=key(collection,oid);old=before.get(k)
            merged=merge_over_existing(payload,old,stated[collection,oid])
            reference_only=False
            if collection=='viewpoint_relations' and old and old.get('review_status') in {'human_approved','approved'}:
                from backend.pipeline.cvp_scope_management import approved_relation_package_reference_only
                reference_only=approved_relation_package_reference_only(package,k,old,merged)
            expected[k]=merged if reference_only else preserve_human_review(merged,old)
    post = deepcopy(before)
    seen = set()
    for op in plan["operations"]:
        k = key(op["collection"], op["object_id"])
        if k in seen or k not in expected or op["operation"] not in {"create", "update"}:
            raise ValueError("duplicate, deleted, or foreign operation")
        if record_content_sha(op["payload"]) != record_content_sha(expected[k]):
            raise ValueError("stored payload differs from the approved final postimage")
        old = before.get(k)
        if op["before_revision"] != (old.get("revision", 1) if old else None):
            raise ValueError("plan base version differs")
        if op["after_revision"] != (old.get("revision", 1) + 1 if old else 1):
            raise ValueError("plan next version differs")
        post[k] = {**op["payload"], "revision": op["after_revision"]}
        seen.add(k)
    for k, p in expected.items():
        if k not in seen and (k not in before or record_content_sha(before[k]) != record_content_sha(p)):
            raise ValueError("plan omitted a reviewed change")
    return post
